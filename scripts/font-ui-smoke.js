(async () => {
  const checks = [];
  const wait = async test => { for (let i = 0; i < 160; i++) { if (test()) return; await new Promise(r => setTimeout(r, 40)); } throw new Error('Font UI wait timeout'); };
  const assert = (condition, label) => { if (!condition) throw new Error(label); checks.push(label); };
  const el = id => document.getElementById(id);
  const scale = () => Number(getComputedStyle(document.documentElement).getPropertyValue('--font-scale'));
  const changeFont = value => { el('setting-font-scale').value = String(value); el('setting-font-scale').dispatchEvent(new Event('input', { bubbles: true })); };
  const noOverflow = () => document.documentElement.scrollWidth <= innerWidth + 1 && el('main-scroll').scrollWidth <= el('main-scroll').clientWidth + 1;
  await wait(() => window.App?.state.photos.length === 16);
  assert(App.api.isDemo, 'Synthetic-only font test');
  assert(scale() === 1.2 && (await App.api.getSettings()).fontScale === 1.2, 'Default font scale is 120 percent');
  assert(parseFloat(getComputedStyle(document.querySelector('.photo-name')).fontSize) >= 14 && parseFloat(getComputedStyle(document.querySelector('.photo-date')).fontSize) >= 12 && parseFloat(getComputedStyle(document.querySelector('.photo-tags')).fontSize) >= 12, 'Functional labels have readable default sizes');
  assert(noOverflow(), 'Default scale has no horizontal overflow');
  el('settings-button').click(); await wait(() => el('setting-font-scale'));
  assert(el('setting-font-scale').min === '1' && el('setting-font-scale').max === '1.5' && el('setting-font-scale').step === '0.1', 'Settings supports 100 to 150 percent in 10 percent steps');
  changeFont(1.5);
  assert(scale() === 1.5 && el('setting-font-value').textContent === '150%', 'Slider previews all text immediately');
  assert(noOverflow(), '150 percent has no horizontal overflow');
  el('settings-cancel').click();
  assert(scale() === 1.2 && (await App.api.getSettings()).fontScale === 1.2, 'Cancel restores saved scale without persistence');
  el('settings-button').click(); await wait(() => el('setting-font-scale')); changeFont(1.4); el('settings-save').click();
  await wait(() => !el('setting-font-scale'));
  assert(scale() === 1.4 && (await App.api.getSettings()).fontScale === 1.4, 'Save persists font scale through settings API');
  el('settings-button').click(); await wait(() => el('setting-font-scale'));
  assert(Number(el('setting-font-scale').value) === 1.4, 'Settings reopens at saved scale');
  changeFont(1); el('settings-cancel').click();
  assert(scale() === 1.4, 'Cancel returns to most recently saved scale');
  assert(App.applyFontScale(8) === 1.5 && App.applyFontScale(-2) === 1 && App.applyFontScale('invalid') === 1.2, 'Font scale clamps invalid and out of range values safely');
  await App.api.saveSettings({ fontScale: 1.2 }); App.state.settings.fontScale = 1.2; App.applyFontScale(1.2);
  document.querySelector('[data-view="favorites"]').click();
  App.applyFontScale(1.5);
  assert(noOverflow(), 'Favorites and SD toolbar wrap at maximum scale');
  App.applyFontScale(1.2); document.querySelector('[data-view="all"]').click(); el('toast-root').replaceChildren();
  return { passed: checks.length, checks, viewport: { width: innerWidth, height: innerHeight } };
})();
