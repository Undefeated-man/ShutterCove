(async () => {
  const checks = [];
  const assert = (condition, label) => { if (!condition) throw new Error(label); checks.push(label); };
  const wait = async condition => {
    for (let attempt = 0; attempt < 180; attempt++) {
      if (condition()) return;
      await new Promise(resolve => setTimeout(resolve, 25));
    }
    const scroll = document.getElementById('main-scroll'), toolbar = document.getElementById('gallery-toolbar'), first = document.getElementById('photo-grid')?.firstElementChild;
    throw new Error(`Sticky toolbar UI wait timeout: ${condition.toString()} ${JSON.stringify({ scrollTop: scroll?.scrollTop, viewport: scroll?.getBoundingClientRect().toJSON(), toolbar: toolbar?.getBoundingClientRect().toJSON(), inset: window.App?.galleryInset?.(), first: first?.getBoundingClientRect().toJSON(), page: window.App?.state.visible })}`);
  };
  const frames = () => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
  const el = id => document.getElementById(id);
  await wait(() => window.App?.api.isDemo && App.galleryInset && window.PhotoTimeline && App.state.photos.length && !App.state.scanning);
  const api = App.api, scroll = el('main-scroll'), toolbar = el('gallery-toolbar');
  const originalScan = api.scan;
  const original = { root: App.state.root, view: App.state.view, visible: App.state.visible, selected: new Set(App.state.selected), scale: getComputedStyle(document.documentElement).getPropertyValue('--font-scale') };
  const controls = ['search', 'date-from', 'date-to', 'theme-filter', 'tag-filter', 'color-filter', 'sort-order'];
  const values = Object.fromEntries(controls.map(id => [id, el(id).value]));
  const base = await originalScan(original.root);
  const photos = Array.from({ length: 300 }, (_, index) => ({
    ...base.photos[index % base.photos.length], id: `demo-${index}`,
    name: `固顶-${String(index).padStart(3, '0')}.JPG`, stem: `固顶-${String(index).padStart(3, '0')}`,
    date: new Date(Date.UTC(2026, 9, 1) - index * 86400000).toISOString().slice(0, 10),
    favorite: index % 2 === 0,
  }));
  const visibleTop = () => Math.max(scroll.getBoundingClientRect().top + App.galleryInset(), toolbar.getBoundingClientRect().bottom + 10);
  const cardVisible = card => card && card.getBoundingClientRect().top >= visibleTop() - 2 && card.getBoundingClientRect().top < scroll.getBoundingClientRect().bottom - 40;
  const pinned = () => toolbar.getBoundingClientRect().top >= scroll.getBoundingClientRect().top - 1 && toolbar.getBoundingClientRect().top <= scroll.getBoundingClientRect().top + 1;
  const key = (node, value, extra = {}) => node.dispatchEvent(new KeyboardEvent('keydown', { key: value, bubbles: true, ...extra }));
  const mouse = node => {
    if (!node) throw new Error(`Missing mouse target after ${checks.at(-1)}; menu=${el('glass-dropdown')?.textContent}; calendar=${!!el('date-calendar')}`);
    const rect = node.getBoundingClientRect(), point = { bubbles: true, button: 0, clientX: rect.left + rect.width / 2, clientY: rect.top + rect.height / 2 };
    node.dispatchEvent(new PointerEvent('pointermove', point));
    node.dispatchEvent(new PointerEvent('pointerdown', point));
    // Synthetic click does not perform the browser's native focus step. Seed the
    // visible control's focus so the subsequent application focus calls are tested.
    if (node.matches('button,input')) node.focus({ preventScroll: true });
    node.dispatchEvent(new PointerEvent('pointerup', point));
    node.click();
  };
  const keptScroll = async (before, label) => {
    await frames();
    await frames();
    assert(Math.abs(scroll.scrollTop - before) < 2 && pinned(), `${label} (scroll ${before} → ${scroll.scrollTop})`);
  };
  try {
    api.scan = async root => ({ root, photos });
    el('reset-filters').click();
    el('sort-order').value = 'date-desc';
    document.querySelector('[data-view="all"]').click();
    await App.refresh(original.root);
    await frames();
    assert(getComputedStyle(toolbar).position === 'sticky', 'Gallery heading and filters share a sticky toolbar');
    scroll.scrollTo({ top: 4000, behavior: 'instant' });
    await wait(pinned);
    await frames();
    assert(toolbar.classList.contains('is-stuck') && toolbar.contains(el('search')) && toolbar.contains(el('select-mode')) && toolbar.contains(el('sort-order')), 'After scrolling, search, multi-select and sort stay in the pinned toolbar');
    const firstTop = toolbar.getBoundingClientRect().top;
    scroll.scrollTo({ top: 6000, behavior: 'instant' });
    await frames();
    assert(Math.abs(toolbar.getBoundingClientRect().top - firstTop) <= 1, 'Toolbar remains at the viewport top across long gallery scrolling');
    const beforeRender = scroll.scrollTop;
    App.render();
    await frames();
    assert(Math.abs(scroll.scrollTop - beforeRender) < 2, 'Ordinary gallery renders preserve the current scroll position');
    App.applyFontScale(1.5);
    await frames();
    await wait(() => Math.abs(parseFloat(getComputedStyle(scroll).scrollPaddingTop) - App.galleryInset()) <= 1);
    assert(App.galleryInset() >= toolbar.getBoundingClientRect().height + 11 && toolbar.getBoundingClientRect().bottom < scroll.getBoundingClientRect().bottom - 100, '150 percent toolbar height is measured dynamically and leaves room for photos');
    assert(scroll.scrollWidth <= scroll.clientWidth + 1 && document.documentElement.scrollWidth <= innerWidth + 1, '150 percent compact toolbar has no horizontal overflow');
    const range = el('date-from').closest('.date-range');
    assert(range.scrollWidth <= range.clientWidth + 1 && range.getBoundingClientRect().right <= toolbar.getBoundingClientRect().right + 1, 'The non-wrapping date range fits inside the 150 percent compact toolbar');
    const jumped = await PhotoTimeline.jump(230);
    const target = document.querySelector('.photo-card[data-id="demo-230"]');
    assert(jumped?.index === 230 && App.state.visible === 240 && cardVisible(target), 'A timeline jump places its off-page target below the sticky toolbar');
    scroll.scrollTo({ top: scroll.scrollTop + 95, behavior: 'instant' });
    await frames();
    const cards = [...el('photo-grid').querySelectorAll('.photo-card')];
    const firstVisible = cards.findIndex(card => card.getBoundingClientRect().bottom > scroll.getBoundingClientRect().top + App.galleryInset());
    assert(PhotoTimeline.current().index === App.state.visible - 120 + firstVisible, 'Timeline current date tracks the first photo below the toolbar rather than a covered photo');
    const firstJump = await PhotoTimeline.jump(0);
    assert(firstJump?.index === 0 && cardVisible(document.querySelector('.photo-card[data-id="demo-0"]')), 'Jumping to the first photo respects the toolbar while scrolling past the cover');
    await PhotoTimeline.jump(230);
    el('load-more').click();
    await wait(() => App.state.visible === 360 && cardVisible(el('photo-grid').firstElementChild));
    assert(el('photo-grid').firstElementChild.dataset.id === 'demo-240', 'Next page scrolls its first photo below the toolbar');
    el('previous-page').click();
    await wait(() => App.state.visible === 240 && cardVisible(el('photo-grid').firstElementChild));
    assert(el('photo-grid').firstElementChild.dataset.id === 'demo-120', 'Previous page also respects the sticky toolbar offset');
    scroll.scrollTo({ top: 5000, behavior: 'instant' });
    await frames();
    const firstCard = el('photo-grid').firstElementChild;
    firstCard.focus();
    await wait(() => firstCard.getBoundingClientRect().top >= visibleTop() - 2);
    assert(document.activeElement === firstCard, 'Keyboard focus brings a photo into view below the sticky toolbar');
    scroll.scrollTo({ top: 5000, behavior: 'instant' });
    await frames();
    document.querySelector('[data-view="favorites"]').click();
    await frames();
    assert(App.state.view === 'favorites' && App.state.visible === 120 && scroll.scrollTop === 0 && App.state.filtered.length === 150, 'Changing to favorites resets page and scroll without losing the full filtered library');
    assert(el('hero').hidden && toolbar.contains(el('view-title')), 'Favorites title and filters remain in the shared toolbar');
    document.querySelector('[data-view="all"]').click();
    await frames();
    assert(scroll.scrollTop === 0 && !el('hero').hidden, 'Returning to all memories restores the cover and the start of the gallery');
    scroll.scrollTo({ top: 4000, behavior: 'instant' });
    await wait(pinned);
    el('select-mode').click();
    assert(App.state.selectionMode && el('select-mode').textContent === '完成多选', 'Pinned multi-select control remains usable at 150 percent');
    const selectable = [...el('photo-grid').querySelectorAll('.photo-card')].find(card => cardVisible(card));
    assert(!!selectable, 'A visible photo remains available below the fixed toolbar');
    selectable.querySelector('.photo-select').click();
    const modeRect = el('select-mode').getBoundingClientRect(), hit = document.elementFromPoint(modeRect.left + modeRect.width / 2, modeRect.top + modeRect.height / 2);
    assert(!el('selection-bar').hidden && App.state.selected.size === 1 && (hit === el('select-mode') || el('select-mode').contains(hit)), 'Expanded bottom selection controls do not block pinned multi-select clicks');
    el('select-mode').click();
    await frames();
    await frames();
    const colorSelect = el('color-filter');
    const colorTop = scroll.scrollTop;
    GlassDropdown.open(colorSelect);
    await wait(() => el('glass-dropdown'));
    await keptScroll(colorTop, 'Dropdown API opening preserves deep scroll and the pinned toolbar');
    const menu = el('glass-dropdown'), menuRect = menu.getBoundingClientRect();
    assert(menuRect.top >= 0 && menuRect.bottom <= innerHeight + 1 && Number(getComputedStyle(menu).zIndex) > Number(getComputedStyle(toolbar).zIndex), 'Dropdown portal appears above the pinned toolbar inside the compact window');
    document.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
    assert(!el('glass-dropdown') && document.activeElement === colorSelect.nextElementSibling, 'Dropdown Escape restores focus to its pinned trigger');
    await keptScroll(colorTop, 'Dropdown Escape focus restoration preserves the gallery position');
    const sortTrigger = el('sort-order').nextElementSibling, sortTop = scroll.scrollTop;
    sortTrigger.focus({ preventScroll: true });
    key(sortTrigger, 'ArrowDown');
    await wait(() => el('glass-dropdown'));
    await keptScroll(sortTop, 'Keyboard sort-menu opening keeps the deep gallery position');
    key(sortTrigger, 'Home');
    key(sortTrigger, 'Enter');
    await wait(() => !el('glass-dropdown'));
    assert(document.activeElement === sortTrigger && el('sort-order').value === 'date-desc', 'Keyboard choice returns focus to the pinned sorting control');
    await keptScroll(sortTop, 'Keyboard sort selection and trigger focus preserve scroll');
    const tagSelect = el('tag-filter'), tagTrigger = tagSelect.nextElementSibling, tagTop = scroll.scrollTop;
    mouse(tagTrigger);
    await wait(() => el('glass-dropdown') && document.querySelector('.glass-dropdown-search input'));
    assert(document.activeElement === document.querySelector('.glass-dropdown-search input'), 'Mouse opening of a long tag menu focuses its portal search');
    await keptScroll(tagTop, 'Mouse opening and portal-search focus preserve deep scroll');
    const optionSearch = document.querySelector('.glass-dropdown-search input');
    mouse(optionSearch);
    optionSearch.value = '全部标签';
    optionSearch.dispatchEvent(new Event('input', { bubbles: true }));
    const allTags = document.querySelector('.glass-dropdown-option');
    mouse(allTags);
    await wait(() => !el('glass-dropdown'));
    assert(tagSelect.value === '' && document.activeElement === tagTrigger && App.state.filtered.length === 300, 'Mouse hover and tag choice return focus without changing the complete gallery');
    await keptScroll(tagTop, 'Mouse tag choice and trigger focus preserve deep scroll');
    const dateTop = scroll.scrollTop;
    mouse(document.querySelector('[data-date-picker="date-from"]'));
    await wait(() => el('date-calendar'));
    await keptScroll(dateTop, 'Mouse calendar opening and initial year focus preserve deep scroll');
    const calendar = el('date-calendar'), calendarRect = calendar.getBoundingClientRect();
    assert(calendarRect.top >= 0 && calendarRect.bottom <= innerHeight + 1 && Number(getComputedStyle(calendar).zIndex) > Number(getComputedStyle(toolbar).zIndex), 'Calendar portal stays visible above the fixed controls');
    const monthSelect = document.querySelector('.calendar-month');
    mouse(monthSelect.nextElementSibling);
    await wait(() => el('glass-dropdown'));
    mouse(document.querySelector('.glass-dropdown-option[aria-selected="true"]'));
    await wait(() => !el('glass-dropdown'));
    assert(!!el('date-calendar') && document.activeElement === document.querySelector('.calendar-month').nextElementSibling, 'Calendar month selection restores focus to its rebuilt control');
    await keptScroll(dateTop, 'Rebuilt month-control focus keeps the gallery pinned');
    key(document.activeElement, 'Escape');
    assert(!el('date-calendar') && document.activeElement === el('date-from'), 'Calendar Escape returns focus to its pinned date input');
    await keptScroll(dateTop, 'Calendar Escape input focus does not pull the gallery back to its cover');
    el('date-from').focus({ preventScroll: true });
    key(el('date-from'), 'ArrowDown', { altKey: true });
    await wait(() => el('date-calendar'));
    await keptScroll(dateTop, 'Keyboard calendar opening preserves deep scroll');
    mouse(document.querySelector('.date-calendar-close'));
    assert(!el('date-calendar') && document.activeElement === el('date-from'), 'Mouse calendar close returns focus to the pinned date input');
    await keptScroll(dateTop, 'Mouse calendar close and input focus preserve deep scroll');
    el('search').value = '固顶-299';
    el('search').dispatchEvent(new Event('input', { bubbles: true }));
    await frames();
    assert(App.state.filtered.length === 1 && App.state.filtered[0].id === 'demo-299' && toolbar.contains(el('search')), 'Search in the pinned toolbar finds a photo beyond the first page');
  } catch (error) {
    throw new Error(`Sticky toolbar regression failed after ${checks.at(-1)}: ${error.message}; ${error.stack}`);
  } finally {
    GlassDropdown.close();
    DateCalendar.close();
    api.scan = originalScan;
    App.applyFontScale(original.scale);
    el('reset-filters').click();
    for (const id of controls) el(id).value = values[id];
    document.querySelector(`[data-view="${original.view}"]`)?.click();
    await App.refresh(original.root);
    App.state.visible = original.visible;
    App.state.selected = original.selected;
    App.render();
    scroll.scrollTo({ top: 0, behavior: 'instant' });
  }
  return { passed: checks.length, checks, fixture: { groups: 300, favorites: 150 }, viewport: { width: innerWidth, height: innerHeight } };
})();
