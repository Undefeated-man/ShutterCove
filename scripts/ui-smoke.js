(async () => {
  const checks = [];
  const wait = async condition => {
    for (let i = 0; i < 160; i++) { if (condition()) return; await new Promise(r => setTimeout(r, 50)); }
    throw new Error('UI wait timed out');
  };
  const assert = (condition, label) => { if (!condition) throw new Error(label); checks.push(label); };
  const el = id => document.getElementById(id);
  const change = (id, value) => { el(id).value = value; el(id).dispatchEvent(new Event('change', { bubbles: true })); };
  await wait(() => window.App?.state.photos.length >= 16);
  await wait(() => document.querySelector('.photo-card img')?.naturalWidth > 0);
  assert(App.api.isDemo, 'Synthetic-only UI test');
  assert(App.state.filtered.length === 16, 'Gallery loaded with paired sample photos');
  change('date-from', '2025-09-24');
  assert(App.state.filtered.every(p => p.date >= '2025-09-24') && App.state.filtered.length === 4, 'Date range filter');
  change('theme-filter', '山川与湖泊');
  assert(App.state.filtered.length === 2, 'Theme and date filters combine');
  el('reset-filters').click();
  change('tag-filter', '湖泊');
  assert(App.state.filtered.length > 0 && App.state.filtered.every(p => p.tags.includes('湖泊')), 'Tag filter');
  el('reset-filters').click();
  change('color-filter', 'green');
  assert(App.state.filtered.length === 3, 'Color family filter');
  document.querySelector('[data-view="favorites"]').click();
  assert(App.state.filtered.every(p => p.favorite && p.colorFamily === 'green'), 'Favorites respect shared filters');
  el('reset-filters').click();
  document.querySelector('[data-view="all"]').click();
  document.querySelectorAll('.photo-select')[0].click();
  document.querySelectorAll('.photo-select')[1].click();
  assert(App.state.selected.size === 2 && !el('selection-bar').hidden, 'Batch selection');
  const ids = [...App.state.selected];
  await App.update(ids, { addTags: ['合成验收'], favorite: true });
  assert(ids.every(id => App.state.photos.find(p => p.id === id).tags.includes('合成验收')), 'Batch tags and favorite update');
  el('batch-collage').click();
  await wait(() => el('collage-canvas')?.width > 0);
  for (const template of ['grid4', 'grid9', 'vertical', 'horizontal', 'poster', 'film']) {
    change('collage-template', template);
    assert(el('collage-canvas').width > 0 && el('collage-canvas').height > 0, `Collage template ${template}`);
  }
  const thumbs = document.querySelectorAll('.collage-thumb');
  const first = thumbs[0].querySelector('img').alt;
  const dt = new DataTransfer();
  thumbs[0].dispatchEvent(new DragEvent('dragstart', { bubbles: true, dataTransfer: dt }));
  thumbs[1].dispatchEvent(new DragEvent('drop', { bubbles: true, dataTransfer: dt }));
  assert(document.querySelectorAll('.collage-thumb')[1].querySelector('img').alt === first, 'Drag reorders collage');
  let saved = null;
  App.api.saveImage = async args => { saved = args; return { canceled: false, path: 'synthetic-output.jpg' }; };
  el('collage-export').click();
  await wait(() => saved !== null && !el('collage-canvas'));
  assert(saved.dataUrl.startsWith('data:image/jpeg;base64,'), 'Collage export is a JPEG');
  el('clear-selection').click();
  document.querySelector('.photo-card').click();
  await wait(() => el('inspect-edit'));
  assert(!!el('preview-jpeg') && !!el('preview-raw'), 'Inspector shows JPEG and CR3 previews together');
  el('inspect-edit').click();
  await wait(() => el('edit-canvas')?.width > 0);
  const before = [el('edit-canvas').width, el('edit-canvas').height];
  el('rotate-right').click();
  assert(el('edit-canvas').width === before[1] && el('edit-canvas').height === before[0], 'Editor rotation');
  el('flip-horizontal').click();
  el('edit-undo').click();
  assert(el('edit-canvas').width === before[1], 'Mirror and undo');
  const drawRegion = (tool, dx, dy) => {
    el(tool).click();
    const c = el('edit-canvas'), rect = c.getBoundingClientRect();
    c.setPointerCapture = () => {};
    c.onpointerdown(new PointerEvent('pointerdown', { clientX: rect.left + rect.width * .1, clientY: rect.top + rect.height * .1, pointerId: 1 }));
    c.onpointermove(new PointerEvent('pointermove', { clientX: rect.left + rect.width * dx, clientY: rect.top + rect.height * dy, pointerId: 1 }));
    c.onpointerup(new PointerEvent('pointerup', { clientX: rect.left + rect.width * dx, clientY: rect.top + rect.height * dy, pointerId: 1 }));
  };
  drawRegion('mosaic-rect', .55, .6);
  assert(!el('edit-undo').disabled, 'Rectangle mosaic creates undo step');
  drawRegion('mosaic-ellipse', .6, .7);
  drawRegion('crop-tool', .8, .8);
  el('apply-crop').click();
  assert(el('edit-canvas').width < before[1], 'Editor crop');
  saved = null;
  el('edit-save-as').click();
  await wait(() => saved !== null && !el('edit-canvas'));
  assert(saved.dataUrl.startsWith('data:image/jpeg;base64,') && !saved.overwriteId, 'Editing save-as preserves original');
  document.querySelectorAll('.photo-select')[0].click();
  document.querySelector('[data-view="similar"]').click();
  el('start-similar').click();
  await wait(() => App.state.similar?.length > 0);
  assert(App.state.similar.length === 15 && App.state.similar[0].similarity >= App.state.similar.at(-1).similarity, 'Similarity results ranked with progress');
  el('clear-selection').click();
  document.querySelector('[data-view="all"]').click();
  el('main-scroll').scrollTop = 0;
  el('toast-root').replaceChildren();
  await wait(() => [...document.querySelectorAll('.photo-card img')].slice(0, 4).every(i => i.naturalWidth > 0 && i.classList.contains('loaded')));
  await new Promise(r => setTimeout(r, 650));
  return { passed: checks.length, checks, imagesDecoded: [...document.querySelectorAll('.photo-card img')].filter(i => i.naturalWidth > 0).length };
})();
