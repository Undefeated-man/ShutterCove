(async () => {
  const checks=[];
  const wait=async test=>{for(let i=0;i<160;i++){if(test())return;await new Promise(r=>setTimeout(r,40));}throw new Error('Date UI wait timeout');};
  const assert=(ok,name)=>{if(!ok)throw new Error(name);checks.push(name);};
  const el=id=>document.getElementById(id);
  const change=(input,value)=>{input.value=value;input.dispatchEvent(new Event('change',{bubbles:true}));};
  await wait(()=>window.App?.state.photos.length===16&&window.DateCalendar);
  assert(App.api.isDemo,'Synthetic-only date test');
  assert(el('date-from').type==='text'&&el('date-to').type==='text','Date inputs support direct text entry with unchanged IDs');
  document.querySelector('[data-date-picker="date-from"]').click();
  assert(!!el('date-calendar')&&document.querySelectorAll('.calendar-day').length===42,'Glass calendar opens with complete week grid');
  change(document.querySelector('.calendar-year'),'2025');change(document.querySelector('.calendar-month'),'8');
  document.querySelector('[data-date="2025-09-24"]').click();
  assert(el('date-from').value==='2025-09-24'&&App.state.filtered.length===4&&!el('date-calendar'),'Clicking a day stores ISO date and filters gallery');
  change(el('date-from'),'2025/09/23');
  assert(el('date-from').value==='2025-09-23'&&App.state.filtered.length===6,'Direct slash date normalizes before filter execution');
  change(el('date-to'),'2025-09-24');
  assert(App.state.filtered.length===4,'Typed start and end dates combine correctly');
  change(el('date-from'),'invalid');
  assert(el('date-from').value==='2025-09-23'&&App.state.filtered.length===4,'Invalid date restores last valid filter');
  document.querySelector('[data-date-picker="date-from"]').click();
  change(document.querySelector('.calendar-year'),'2025.4');
  assert(document.querySelector('.calendar-year').value==='2025','Year selector clamps to an integer');
  document.querySelector('[data-month-step="-1"]').click();
  assert(document.querySelector('.calendar-month').value==='7','Previous month navigation');
  document.querySelector('[data-month-step="1"]').click();
  assert(document.querySelector('.calendar-month').value==='8','Next month navigation');
  document.querySelector('[data-calendar-clear]').click();
  assert(el('date-from').value===''&&!el('date-calendar'),'Calendar clear removes date restriction');
  document.querySelector('[data-date-picker="date-to"]').click();
  document.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}));
  assert(!el('date-calendar'),'Escape closes calendar');
  document.querySelector('[data-date-picker="date-to"]').click();
  el('view-title').dispatchEvent(new PointerEvent('pointerdown',{bubbles:true}));
  assert(!el('date-calendar'),'Outside click closes calendar');
  document.querySelector('[data-date-picker="date-from"]').click();
  document.querySelector('[data-calendar-today]').click();
  const now=new Date(),today=now.getFullYear()+'-'+String(now.getMonth()+1).padStart(2,'0')+'-'+String(now.getDate()).padStart(2,'0');
  assert(el('date-from').value===today,'Today action selects current calendar date');
  el('reset-filters').click();
  assert(App.state.filtered.length===16,'Reset preserves full gallery behavior');
  change(el('date-from'),'invalid');assert(el('date-from').value===''&&App.state.filtered.length===16,'Reset clears last valid date so invalid input cannot restore an old restriction');
  assert(document.documentElement.scrollWidth<=innerWidth+1&&el('main-scroll').scrollWidth<=el('main-scroll').clientWidth+1,'Calendar controls fit compact window without horizontal overflow');
  assert(DateCalendar.parse('2024-02-29')!==null&&DateCalendar.parse('2025-02-29')===null,'Calendar validates leap dates');
  el('toast-root').replaceChildren();return {passed:checks.length,checks,viewport:{width:innerWidth,height:innerHeight}};
})();
